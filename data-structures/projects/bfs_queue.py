from collections import deque

def bfs(maze, n, m):
# def — ключевое слово определения функции
# bfs — имя функции (breadth-first search)
# ( — открывающая скобка параметров
# maze — параметр (лабиринт)
# , — разделитель
# n — количество строк
# , — разделитель
# m — количество столбцов
# ) — закрывающая скобка
# : — двоеточие, начало тела функции

    # Если старт — стена, пути нет
    if maze[0][0] == 1:
    # if — условный оператор
    # maze[0][0] — стартовая клетка
    # == — сравнение
    # 1 — стена
    # : — двоеточие

        return -1
        # return — ключевое слово возврата
        # -1 — пути нет

    # Матрица расстояний, заполненная -1 (не посещено)
    dist = [[-1] * m for _ in range(n)]
    # dist — имя переменной (расстояния)
    # = — присваивание
    # [ — открывающая скобка списка
    # [-1] * m — список из m элементов -1
    # for _ in range(n) — повтор n раз (_ — игнорируемая переменная)
    # ] — закрывающая скобка

    dist[0][0] = 0
    # dist[0][0] — расстояние до старта
    # = — присваивание
    # 0 — старт

    queue = deque([(0, 0)])
    # queue — очередь
    # = — присваивание
    # deque([(0, 0)]) — создание очереди с начальной точкой
    # (0, 0) — кортеж-координата

    directions = [(-1, 0), (1, 0), (0, -1), (0, 1)]
    # directions — направления движения
    # = — присваивание
    # [ — список
    # (-1, 0) — вверх
    # (1, 0) — вниз
    # (0, -1) — влево
    # (0, 1) — вправо
    # ] — закрывающая скобка

    while queue:
    # while — цикл, пока очередь не пуста

        r, c = queue.popleft()
        # r — строка (row)
        # , — разделитель
        # c — столбец (column)
        # = — присваивание
        # queue.popleft() — извлечение из начала — O(1)
        # Распаковка кортежа в две переменные

        for dr, dc in directions:
        # for — цикл по направлениям
        # dr — смещение по строке
        # , — разделитель
        # dc — смещение по столбцу
        # in directions — по списку направлений
        # : — двоеточие

            nr = r + dr
            # nr — новая строка
            # = — присваивание
            # r + dr — сумма

            nc = c + dc
            # nc — новый столбец
            # = — присваивание
            # c + dc — сумма

            # Проверка границ
            if not (0 <= nr < n and 0 <= nc < m):
            # if — условный оператор
            # not — отрицание
            # (0 <= nr < n) — проверка диапазона строк
            # and — логическое И
            # (0 <= nc < m) — проверка диапазона столбцов
            # : — двоеточие

                continue
                # continue — переход к следующей итерации

            # Проверка стены
            if maze[nr][nc] == 1:
            # if — условный оператор
            # maze[nr][nc] — значение клетки
            # == 1 — стена
            # : — двоеточие

                continue
                # continue — пропускаем стену

            # Проверка посещения
            if dist[nr][nc] != -1:
            # if — условный оператор
            # dist[nr][nc] — расстояние до клетки
            # != -1 — уже посещена
            # : — двоеточие

                continue
                # continue — пропускаем

            # Обновляем расстояние и добавляем в очередь
            dist[nr][nc] = dist[r][c] + 1
            # dist[nr][nc] — расстояние до новой клетки
            # = — присваивание
            # dist[r][c] + 1 — расстояние до текущей + 1 шаг

            queue.append((nr, nc))
            # queue.append — добавление в конец очереди
            # (nr, nc) — кортеж-координата

    return dist[n - 1][m - 1]
    # return — возврат значения
    # dist[n-1][m-1] — расстояние до финиша (или -1, если не достигнут)

maze = [
    [0, 0, 0, 1],
    [0, 1, 0, 4],
    [0, 0, 0, 5]
]
print(bfs(maze, 3, 3))  # Вывод: 4